/**
 * Prefixes an internal path with the configured base path so links work both
 * under a GitHub Pages repository subpath (e.g. /gecris-website/about) and at
 * a root domain (/about). Always use this for internal links and /public assets.
 */
export function url(path = '/'): string {
  if (/^(https?:|mailto:|tel:|#)/.test(path)) return path;
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  let [clean, hash = ''] = (path.startsWith('/') ? path : `/${path}`).split('#');
  // Pages are built as folders (/about/index.html): link to /about/ to avoid a redirect.
  if (!clean.endsWith('/') && !/\.[a-z0-9]+$/i.test(clean)) clean += '/';
  const suffix = hash ? `#${hash}` : '';
  // Already prefixed (e.g. optimised asset URLs generated by Astro)
  if (base && clean.startsWith(`${base}/`)) return clean + suffix;
  return `${base}${clean}${suffix}`;
}

/** True when `href` matches the current page (used for active nav state). */
export function isActive(href: string, pathname: string): boolean {
  const strip = (p: string) => p.replace(/\/$/, '') || '/';
  const target = strip(url(href));
  const current = strip(pathname);
  if (target === strip(url('/'))) return current === target;
  return current === target || current.startsWith(`${target}/`);
}

export function formatDate(value: string | Date | null | undefined, fallback = 'To be confirmed'): string {
  if (!value) return fallback;
  const d = typeof value === 'string' ? new Date(value) : value;
  if (Number.isNaN(d.getTime())) return fallback;
  return d.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
}
